local mainMod = "ALT"

-- Core Noctalia binds
hl.bind(mainMod .. " + SPACE",  hl.dsp.exec_cmd("noctalia msg panel-toggle launcher"))
hl.bind("SUPER + S",            hl.dsp.exec_cmd("noctalia msg panel-toggle control-center"))
hl.bind("SUPER + comma",        hl.dsp.exec_cmd("noctalia msg settings-toggle"))
hl.bind("SUPER + V",            hl.dsp.exec_cmd("noctalia msg panel-toggle clipboard"))
hl.bind("SUPER + ESCAPE",       hl.dsp.exec_cmd("noctalia msg panel-toggle session"))
hl.bind("SUPER + P",            hl.dsp.exec_cmd("noctalia msg panel-toggle wallpaper"))
hl.bind("SUPER + B",            hl.dsp.exec_cmd("noctalia msg bar-toggle"))
hl.bind("SUPER + O", function()
    local enabled = hl.get_config("decoration.blur.enabled")
    hl.config({
        decoration = {
            blur = {
                enabled = enabled == false or enabled == 0,
            },
        },
    })
end)

-- Media keys
